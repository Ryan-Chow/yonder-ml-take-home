"""Is the ablation difference real? Paired bootstrap over val images, plus 2x2 main effects.

    python scripts/bootstrap_ablation.py [--B 2000]

Every arm is run through the deployment path (src/infer.py) on the grouped-val JPEGs at conf 0.001, AP is computed
with src/apstats.py (verified equal to Ultralytics' compute_ap), and the SAME image resample is applied to all arms
in each bootstrap replicate, so differences are paired. Writes results/ablation.md and results/ablation.json.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.apstats import ap_per_class, image_tp, summarize  # noqa: E402
from src.data_utils import CLASS_NAMES, ROOT, load_split  # noqa: E402
from src.infer import detect, is_finished, load_model  # noqa: E402

ARMS = {  # name: (weights, CLAHE at inference?, description)
    "baseline": ("runs/baseline/weights/best.pt", False, "raw images, default aug"),
    "clahe_only": ("runs/clahe_only/weights/best.pt", True, "CLAHE, default aug"),
    "aug_only": ("runs/aug_only/weights/best.pt", False, "raw images, custom aug"),
    "final": ("weights/best.pt", True, "CLAHE + custom aug (shipped)"),
}
METRICS = ("mAP50", "mAP50-95", "bottle AP50", "mallet AP50", "bottle AP50-95", "mallet AP50-95")


def flat(ap: np.ndarray) -> dict:
    s = summarize(ap)
    out = {"mAP50": s["mAP50"], "mAP50-95": s["mAP50-95"]}
    for c, n in enumerate(CLASS_NAMES):
        out[f"{n} AP50"] = s["ap50"][c]
        out[f"{n} AP50-95"] = s["ap50_95"][c]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--B", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()

    samples = load_split(ROOT / "data" / "split", "valid")
    imgs = [cv2.imread(str(s.image)) for s in samples]
    gts = [np.array([[b.cls, b.xc, b.yc, b.w, b.h] for b in s.boxes]).reshape(-1, 5) for s in samples]
    arms = {k: v for k, v in ARMS.items() if is_finished(ROOT / v[0])}  # never an in-progress checkpoint
    print("arms:", list(arms))
    per_img = {}
    for name, (w, clahe, _) in arms.items():
        preds = detect(load_model(ROOT / w), imgs, conf=0.001, clahe=clahe, device="cpu")
        per_img[name] = [image_tp(p, g) for p, g in zip(preds, gts)]
        print(name, "done")

    point = {k: flat(ap_per_class(v)) for k, v in per_img.items()}
    rng = np.random.default_rng(a.seed)
    n = len(samples)
    boot = {k: {m: [] for m in METRICS} for k in per_img}
    for _ in range(a.B):
        idx = rng.integers(0, n, n)
        for k, items in per_img.items():
            f = flat(ap_per_class([items[i] for i in idx]))
            for m in METRICS:
                boot[k][m].append(f[m])
    boot = {k: {m: np.array(v) for m, v in d.items()} for k, d in boot.items()}

    def ci(x):
        return float(np.percentile(x, 2.5)), float(np.percentile(x, 97.5))

    # cross-check against Ultralytics' validator (results/metrics.json) where available
    ref = json.loads((ROOT / "results" / "metrics.json").read_text()) if (ROOT / "results" / "metrics.json").exists() else {}
    md = ["# Ablation with uncertainty", "",
          f"Generated by `scripts/bootstrap_ablation.py`: {n} grouped-val images, {a.B} paired bootstrap resamples "
          "(images drawn with replacement; the same draw is applied to every arm). Predictions come from the "
          "deployment path (`src/infer.py`, conf >= 0.001). AP uses `src/apstats.py`, tested equal to Ultralytics' "
          "`compute_ap`. Each arm is a single training run (seed 0), so these intervals capture **val-set "
          "sampling noise only, not training-seed noise**. Seed noise would widen them further.", "",
          "## Point estimates (95% bootstrap CI)", "",
          "| arm | " + " | ".join(METRICS) + " |", "|---|" + "---|" * len(METRICS)]
    for k in per_img:
        cells = [f"{point[k][m]:.3f} ({ci(boot[k][m])[0]:.3f}–{ci(boot[k][m])[1]:.3f})" for m in METRICS]
        md.append(f"| {k} ({ARMS[k][2]}) | " + " | ".join(cells) + " |")
    if ref:
        rows = [(k, point[k]["mAP50"], ref[k]["mean"]["mAP50"], point[k]["mAP50-95"], ref[k]["mean"]["mAP50-95"])
                for k in per_img if k in ref]
        md += ["", "Cross-check vs Ultralytics' validator (results/metrics.json): " + "; ".join(
            f"{k}: mAP50 {p50:.4f} vs {r50:.4f}, mAP50-95 {p:.4f} vs {r:.4f}" for k, p50, r50, p, r in rows) + "."]

    md += ["", "## Paired differences vs baseline", "",
           "| comparison | " + " | ".join(METRICS) + " |", "|---|" + "---|" * len(METRICS)]
    res = {"point": point, "diff": {}, "effects": {}}
    for k in [k for k in per_img if k != "baseline"]:
        cells = []
        res["diff"][k] = {}
        for m in METRICS:
            d = boot[k][m] - boot["baseline"][m]
            lo, hi = ci(d)
            pd_ = point[k][m] - point["baseline"][m]
            star = " *" if lo > 0 or hi < 0 else ""
            cells.append(f"{pd_:+.3f} [{lo:+.3f}, {hi:+.3f}]{star}")
            res["diff"][k][m] = {"diff": pd_, "ci": [lo, hi], "p_gt0": float((d > 0).mean())}
        md.append(f"| {k} − baseline | " + " | ".join(cells) + " |")
    md += ["", "`*` = 95% CI excludes zero."]

    if all(k in per_img for k in ARMS):
        md += ["", "## 2x2 main effects (averaged over the other factor)", "",
               "| effect | " + " | ".join(METRICS) + " |", "|---|" + "---|" * len(METRICS)]
        for eff, fn in (
                ("CLAHE", lambda b, m: ((b["clahe_only"][m] - b["baseline"][m]) + (b["final"][m] - b["aug_only"][m])) / 2),
                ("custom aug", lambda b, m: ((b["aug_only"][m] - b["baseline"][m]) + (b["final"][m] - b["clahe_only"][m])) / 2),
                ("interaction", lambda b, m: (b["final"][m] - b["aug_only"][m]) - (b["clahe_only"][m] - b["baseline"][m]))):
            cells = []
            res["effects"][eff] = {}
            for m in METRICS:
                d = fn(boot, m)
                pe = fn({k: {mm: np.array(point[k][mm]) for mm in METRICS} for k in point}, m)
                lo, hi = ci(d)
                cells.append(f"{float(pe):+.3f} [{lo:+.3f}, {hi:+.3f}]{' *' if lo > 0 or hi < 0 else ''}")
                res["effects"][eff][m] = {"effect": float(pe), "ci": [lo, hi]}
            md.append(f"| {eff} | " + " | ".join(cells) + " |")
    (ROOT / "results" / "ablation.md").write_text("\n".join(md) + "\n")
    (ROOT / "results" / "ablation.json").write_text(json.dumps(res, indent=2))
    print("\n".join(md))


if __name__ == "__main__":
    main()
